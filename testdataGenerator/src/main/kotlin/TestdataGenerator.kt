package de.uni_muenster.imi.oegd.testdataGenerator

import io.github.oshai.kotlinlogging.KotlinLogging
import org.redundent.kotlin.xml.Node
import org.redundent.kotlin.xml.xml
import java.io.File
import java.time.LocalDate
import java.time.LocalDateTime
import kotlin.random.Random

private val log = KotlinLogging.logger { }

fun main(args: Array<String>) {
    fun askUser(message: String): String {
        println(message)
        return readln()
    }

    if (!File("testdata").exists()) {
        File("testdata").mkdir()
    }

    val cnt = args.firstOrNull()?.toIntOrNull() ?: askUser("How many patients should be generated?").toInt()
    val patients = TestdataGenerator().createTestdata(cnt)
    patients.forEachIndexed { index, patient ->
        File("testdata/Patient$index").writeText(patient)
    }
}

class TestdataGenerator {
    private var startTimeRange = LocalDate.of(2021, 1, 1)
    private var endTimeRange = LocalDate.of(2022, 2, 28)
    var language: LANGUAGE = LANGUAGE.GERMAN
    private val isEnglish get() = language == LANGUAGE.ENGLISH

    fun setStartYear(year: Int) {
        startTimeRange = LocalDate.of(year, 1, 1)
    }

    fun setEndYear(year: Int) {
        endTimeRange = LocalDate.of(year, 1, 1).minusDays(1)
    }

    fun getStartAndEndYear(): Pair<LocalDateTime, LocalDateTime> {
        return generateStartAndEnddate(startTimeRange, endTimeRange)
    }

    fun createTestdataFile(location: String) {
        val caseScope = CaseScope.entries.random()
        val patient = createPatient(caseScope)
        val id = patient.get<Int>("id").toString()
        File("$location/$id.xml").writeText(patient.toString())
    }

    fun createTestdata(numberOfTestdata: Int): List<String> {
        val result = mutableListOf<String>()
        for (i in 1..numberOfTestdata) {
            val caseScope = CaseScope.entries.random()
            result.add(createPatient(caseScope).toString())
            log.info { "Created new Patient with $caseScope case. Patient no. $i" }
        }
        return result
    }

    fun createPatient(caseScope: CaseScope): Node {
        val caseInfo = CaseInfo(caseScope, this)
        val patient = xml("patient") {
            attribute("birthYear", Random.nextInt(1940, 2010))
            attribute("sex", if (Random.nextBoolean()) 'F' else 'M')
            attribute("id", caseInfo.patientId)
            addCase(caseInfo)
        }
        return patient
    }

    fun Node.addCase(case: CaseInfo) {
        addElement(xml("case") {
            attribute("id", case.caseId)
            attribute("from", case.startDateTime)
            attribute("till", case.endDateTime)
            attribute("type", Casetype.STATIONAER.type)  //filters in app are German
            //TODO: Add AdmissionCause and state
            "location" {
                attribute("id", case.locationId)
                attribute("from", case.startDateTime)
                attribute("till", case.endDateTime)
                attribute("clinic", if (isEnglish) case.clinic.fa_code_en else case.clinic.fa_code)
            }
            "labReport" {
                attribute("id", case.labReportId)
                attribute("source", "MIBI")
                "request" {
                    attribute("from", case.requestDateTime)
                    attribute("sender", if (isEnglish) case.clinic.clinic_en else case.clinic.clinic)
                }
                "sample" {
                    attribute("from", case.requestDateTime)
                    attribute(
                        "bodySiteDisplay",
                        if (isEnglish) case.bodySite.bodySiteDisplay_en else case.bodySite.bodySiteDisplay
                    )
                    attribute("display", if (isEnglish) case.bodySite.display_en else case.bodySite.display)
                    "comment" {
                        -"No comment"
                    }
                    "germ" {
                        attribute("id", case.germId)
                        attribute("SNOMED", case.germType.SNOMED)
                        attribute("display", case.germType.display)
                        attribute("class", case.caseScope.type)
                        "comment" {
                            if (case.caseScope.type != "VRE" || case.germType != GermType.E_FAECALIS) { // do not create VRE for E.faecalis
                                attribute("class", case.caseScope.type) //TODO: Currently xquery searches for this
                            }

                            -"Germ generated by Testdata Generator"
                        }
                        if (case.caseScope == CaseScope.MRSA) {
                            addPCRMetaNode("PatientID", "${case.patientId}")
                            addPCRMetaNode("CaseID", "${case.caseId}")
                            addPCRMetaNode("SampleID", "${case.sampleId}")
                            addPCRMetaNode("CollectionDate", "${case.startDateTime}")
                            addPCRMetaNode("Spa", "${case.spaType?.type}")
                            addPCRMetaNode("ST", "${case.stTypeMRSA?.type}")
                            addPCRMetaNode("ClusterType", "${case.clusterType}")
                        }
                        if (case.caseScope == CaseScope.VRE) {
                            addPCRMetaNode("ST", "${case.stTypeVRE?.type}")
                            addPCRMetaNode("vanA", "${case.stTypeVRE?.type}")
                            addPCRMetaNode("vanB", "${case.stTypeVRE?.type}")
                        }

                        if (case.caseScope in setOf(CaseScope.MRGN3, CaseScope.MRGN4)) {
                            addPCRMetaNode("ST", "${case.stTypeMRGN?.type}")
                        }

                        for ((antibiotic, result) in generateAntibioticsAnalysis(case)) {
                            "antibiotic" {
                                attribute("LOINC", antibiotic.LOINC)
                                attribute("display", if (isEnglish) antibiotic.display_en else antibiotic.display)
                                "result" {
                                    attribute("LOINC", result.LOINC)
                                    attribute("string", result.result)
                                }
                            }
                        }
                    }
                }
            }
            if (case.caseScope == CaseScope.MRSA) {
                "hygiene-message" {
                    attribute("germ-name", case.germType.display)
                    attribute("nosocomial", "${case.nosocomial}")
                    attribute("infection", "${case.infection}")
                    attribute("MDR-class", case.caseScope)
                }
            }
        })
    }


    fun Node.addPCRMetaNode(k: String, v: Any) {
        addElement(xml("pcr-meta") {
            attribute("k", k)
            attribute("v", v)
        })
    }

}

data class CaseInfo(val caseScope: CaseScope, val generator: TestdataGenerator) {
    val patientId: Int = idGenerator.getUniqueId()
    val caseId: Int = idGenerator.getUniqueId()
    val locationId: Int = idGenerator.getUniqueId()
    val labReportId: Int = idGenerator.getUniqueId()
    val sampleId: Int = idGenerator.getUniqueId()
    val germId: Int = idGenerator.getUniqueId()

    val clinic = Department.entries.random()
    val bodySite = SmearType.entries.random()

    private val startAndEndDateTime = generator.getStartAndEndYear()
    val startDateTime: LocalDateTime = startAndEndDateTime.first
    val endDateTime: LocalDateTime = startAndEndDateTime.second
    val requestDateTime: LocalDateTime = startDateTime.plusDays(1) //Request always one day after start

    var germType: GermType
    var spaType: SpaType? = null
    var clusterType: ClusterType? = null
    var nosocomial: Boolean? = null
    var infection: Boolean? = null
    var stTypeMRSA: MRSA_ST? = null
    var stTypeMRGN: ST_MRGN? = null
    var stTypeVRE: VRE_ST? = null
    var vanA: VRE_vanA? = null
    var vanB: VRE_vanB? = null

    init {
        when (caseScope) {
            CaseScope.MRSA -> {
                germType = GermType.S_AUREUS
                spaType = getRandomTypeWithProbability(SpaType.entries)
                clusterType = getRandomTypeWithProbability(ClusterType.entries)
                nosocomial = Random.nextBoolean()
                infection = Random.nextBoolean()
                stTypeMRSA = randomEnum()
            }

            CaseScope.MRGN3, CaseScope.MRGN4 -> {
                germType = MRGNGermTypes.random()
                stTypeMRGN = randomEnum()
            }

            CaseScope.VRE -> {
                germType = VREGermTypes.random()
                vanA = randomEnum()
                vanB = randomEnum()
                stTypeVRE = randomEnum()
            }
        }
    }
}

private inline fun <reified T : ProbabilityEnum> randomEnum(): T {
    return getRandomTypeWithProbability(T::class.java.enumConstants.toList())
}
